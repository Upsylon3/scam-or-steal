const assert = require("node:assert/strict");
global.window = global;
require("../benchmark-data.js");
require("../scoring-engine.js");
const engine = global.PVL_SCORING;
assert.ok(global.PVL_BENCHMARKS.cpuSingleThread.length >= 19, "curated CPU single-thread coverage should include common used-market models");
assert.ok(global.PVL_BENCHMARKS.gpuGaming.length >= 30, "GPU gaming dataset should cover at least 30 cards");
assert.ok(global.PVL_BENCHMARKS.cpuGaming.length >= 7, "CPU gaming dataset should cover CPUs in the current comparable suite");
assert.ok(global.PVL_BENCHMARKS.cpuAppSingleThread.length >= 9, "single-thread application dataset should cover current and used-market CPUs");
assert.ok(global.PVL_BENCHMARKS.cpuAppMultiThread.length >= 9, "multi-thread application dataset should cover current and used-market CPUs");
assert.ok(engine.singleThreadRecord("Intel Core i7-14700KF"), "14700KF should have sourced single-thread data");
const reference = { cpuName: "AMD Ryzen 9 9950X3D", cpu: 70101, gpuName: "GeForce RTX 5090", gpu: 38864 };
const gpu = 12000;
const cpu2600 = { cpuName: "AMD Ryzen 5 2600X", cpuScore: 13860, gpuName: "Radeon RX 6700 XT", gpuScore: gpu };
const cpu5700 = { cpuName: "AMD Ryzen 7 5700X", cpuScore: 26542, gpuName: "Radeon RX 6700 XT", gpuScore: gpu };
const gaming = { cpuShare: 0.35, gpuShare: 0.65, singleMix: 0.75, useGameBenchmarks: true, useCpuGamingBenchmarks: true };
const productivity = { cpuShare: 0.75, gpuShare: 0.25, singleMix: 0.15, useGameBenchmarks: false, useCpuAppBenchmarks: true };
const gamingOld = engine.score(cpu2600, reference, gaming);
const gamingNew = engine.score(cpu5700, reference, gaming);
const productivityOld = engine.score(cpu2600, reference, productivity);
const productivityNew = engine.score(cpu5700, reference, productivity);
assert.ok(gamingNew.idx > gamingOld.idx, "5700X should improve gaming-profile performance with the same GPU");
assert.ok(productivityNew.idx > productivityOld.idx, "5700X should improve productivity-profile performance");
assert.ok(productivityNew.idx - productivityOld.idx > gamingNew.idx - gamingOld.idx, "CPU upgrade should matter more in CPU-heavy productivity than GPU-led gaming");
assert.equal(gamingOld.confidence, "high", "curated CPU and GPU benchmarks should provide stronger evidence");
assert.equal(gamingOld.gpuGamingMeasured, true, "RX 6700 XT should use the sourced gaming benchmark");
assert.equal(gamingOld.gpuPct, 32.5, "1440p raster score should match the curated source record");
assert.equal(engine.score({cpuName:"Unknown CPU",cpuScore:10000,gpuName:"Unknown GPU",gpuScore:gpu}, reference, gaming).confidence, "low", "unlisted CPU/GPU must be marked as lower-confidence fallback");
assert.equal(engine.modelVersion, "performance-v2.3");
const cpuGameComparison = engine.score({cpuName:"AMD Ryzen 7 9800X3D",cpuScore:45000,gpuName:"NVIDIA GeForce RTX 5090",gpuScore:38864}, reference, gaming);
assert.equal(cpuGameComparison.cpuBenchmarkType, "tomCpuGaming", "gaming profile should use the matched Tom's Hardware CPU game suite");
assert.ok(Math.abs(cpuGameComparison.cpuPct - (97 / 95.7 * 100)) < 0.001, "CPU gaming ratio should use the source suite score");
const cpuAppComparison = engine.score({cpuName:"AMD Ryzen 7 5700X",cpuScore:26542,gpuName:"Unknown GPU",gpuScore:gpu}, reference, productivity);
assert.equal(cpuAppComparison.cpuBenchmarkType, "tomCpuApps", "productivity profile should use matched CPU application suites");
assert.ok(Math.abs(cpuAppComparison.cpuPct - ((67 / 92.8 * 100) * 0.15 + (29.5 / 96.2 * 100) * 0.85)) < 0.001, "productivity score should blend the matching app suites");
const unsupportedCpuGame = engine.score(cpu5700, reference, gaming);
assert.equal(unsupportedCpuGame.cpuBenchmarkType, "passmark", "CPU gaming score must fall back rather than infer an unmeasured score");
const customReference = { cpuName: "Custom reference CPU", cpu: 50000, gpu: 38864 };
const customRefResult = engine.score(cpu5700, {...customReference, gpuName: "Custom reference GPU"}, gaming);
assert.ok(customRefResult.cpuSinglePct < 100, "unknown custom reference must safely fall back to CPU Mark ratios rather than raw single-thread scores");
assert.equal(customRefResult.confidence, "low");
const raster4k = engine.score(cpu5700, reference, {...gaming, resolution:"4k", graphicsMode:"raster"});
const rt1440 = engine.score(cpu5700, reference, {...gaming, resolution:"1440p", graphicsMode:"rayTracing"});
assert.equal(raster4k.gpuPct, 25.3, "4K raster should use the selected resolution benchmark");
assert.equal(rt1440.gpuPct, 17.9, "ray tracing should use the separate RT benchmark suite");
assert.notEqual(raster4k.gpuPct, rt1440.gpuPct, "raster and ray tracing are separate benchmark suites");
console.log("Scoring engine tests passed");
